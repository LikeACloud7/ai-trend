const entityMap = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: ' ',
  ndash: '-',
  mdash: '-',
  rsquo: "'",
  lsquo: "'",
  rdquo: '"',
  ldquo: '"',
};

export function decodeHtml(value = '') {
  return String(value)
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (_, entity) => {
      const lower = entity.toLowerCase();
      if (lower.startsWith('#x')) return String.fromCodePoint(Number.parseInt(lower.slice(2), 16));
      if (lower.startsWith('#')) return String.fromCodePoint(Number.parseInt(lower.slice(1), 10));
      return entityMap[lower] ?? `&${entity};`;
    })
    .replace(/\s+/g, ' ')
    .trim();
}

function countPhrase(text, phrase) {
  if (!phrase) return 0;
  const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\s+/g, '\\s+');
  const regex = new RegExp(`(^|[^a-z0-9])${escaped}([^a-z0-9]|$)`, 'gi');
  return Array.from(text.matchAll(regex)).length;
}

export function classifyPaper(paper) {
  const title = `${paper.title ?? ''}`.toLowerCase();
  const abstract = `${paper.abstract ?? ''}`.toLowerCase();
  const keywords = (paper.keywords ?? []).join(' ').toLowerCase();
  const scores = TOPIC_TAXONOMY.filter((topic) => topic.id !== 'other').map((topic) => {
    const score = topic.keywords.reduce((sum, keyword) => {
      return (
        sum +
        countPhrase(title, keyword) * 5 +
        countPhrase(keywords, keyword) * 4 +
        countPhrase(abstract, keyword) * 1
      );
    }, 0);
    return { id: topic.id, label: topic.label, color: topic.color, score };
  });

  const ranked = scores.filter((item) => item.score > 0).sort((a, b) => b.score - a.score);
  const primary = ranked[0] ?? TOPIC_TAXONOMY.find((topic) => topic.id === 'other');
  const secondary = ranked.slice(1, 4).filter((item) => item.score >= Math.max(2, primary.score * 0.35));

  return {
    primaryCategory: primary.id,
    categoryScores: ranked.slice(0, 5),
    categories: [primary.id, ...secondary.map((item) => item.id)],
  };
}

export function getTopic(topicId) {
  return TOPIC_TAXONOMY.find((topic) => topic.id === topicId) ?? TOPIC_TAXONOMY.at(-1);
}
